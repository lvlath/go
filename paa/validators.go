// Package paa validates finite source samples and representable rational
// geometry. This file establishes the public error precedence and rejects
// unrepresentable index products or slice sizes before allocating outputs.

package paa

import "math"

const (
	// segmentInt64Fields counts the three scalar fields in a Segment.
	// It is the storage layout used by the checked output-size calculation;
	// every field is an int64, with no pointers or variable-length content.
	segmentInt64Fields = 3

	// int64StorageBytes is the fixed storage width of Go's int64 type.
	// It is not a platform-dependent int or pointer size and is therefore 8.
	int64StorageBytes = 8

	// segmentStorageBytes is the byte size of one contiguous Segment element.
	// Three consecutive int64 fields occupy 24 bytes, so the bound catches a
	// size-overflow request before make([]Segment, w) would compute its length.
	segmentStorageBytes = segmentInt64Fields * int64StorageBytes
)

// validateTransform accepts only nonempty finite series with valid partition
// counts and representable exact integer geometry. It performs every public
// gate before the kernel is allowed to allocate or interpret endpoint products.
//
// Implementation:
//   - Stage 1: reject nonpositive w, nil input, empty input, and w>n in order.
//   - Stage 2: validate all sample values (including both endpoints) as finite.
//   - Stage 3: ensure n*w fits int64 and w Segment elements fit a Go int byte size.
//
// Behavior highlights:
//   - Earlier failures take precedence even if later data is also invalid.
//   - The n*w bound covers every i*w and j*n endpoint generated by the sweep.
//   - This method validates representability, not available physical RAM.
//
// Inputs:
//   - values: read-only source slice; all positions are inspected for finiteness.
//   - segments: required number w of equal-duration output intervals.
//
// Returns:
//   - error: nil when it is safe to enter the canonical kernel; otherwise
//     the earliest applicable package-owned sentinel.
//
// Errors:
//   - ErrInvalidOption: w<=0, or w>n after source presence checks.
//   - ErrNilInput: absent source; ErrEmptyInput: present zero-length source.
//   - ErrNonFinite: NaN or ±Inf observed at any input position.
//   - ErrOverflow: n*w exceeds int64 or Segment output bytes exceed int.
//
// Determinism:
//   - Strict gate order followed by a left-to-right finite-element scan.
//
// Complexity:
//   - Time O(n), extra space O(1); validation allocates no output buffers.
//
// Notes:
//   - Concurrent caller writes to values during validation or computation
//     are unsupported; the package does not snapshot source storage.
//
// AI-Hints:
//   - Do not replace the n*w guard with a post-multiplication overflow check:
//     the multiplication would already have overflowed before comparison.
//   - All nonfinite elements are rejected before integer-overflow checks,
//     even when the bad value is at the end of a long input.
func validateTransform(values []float64, segments int) error {
	// The count is an input-independent required option: this check must come
	// first, even if the caller supplied no slice at all.
	if segments <= 0 {
		return ErrInvalidOption
	}

	// Presence and shape are distinct observable protocol states. An empty but
	// allocated slice is intentionally not classified as a nil input.
	if values == nil {
		return ErrNilInput
	}
	n := len(values)
	if n == 0 {
		return ErrEmptyInput
	}

	// Only after reading n is the upper bound for the segment count meaningful.
	// Reject it before scanning floats so shape errors keep their precedence.
	if segments > n {
		return ErrInvalidOption
	}

	// All samples must be finite because each input cell has positive measure
	// and the exact overlap scan never ignores a valid last observation.
	for _, v := range values {
		if math.IsNaN(v) || math.IsInf(v, 0) {
			return ErrNonFinite
		}
	}

	// Every source endpoint i*w and segment endpoint j*n is at most n*w.
	// Division-based comparison avoids overflowing a product that would have
	// invalidated all subsequent int64 coordinate operations.
	// A Go int is at most 64 bits on supported architectures; positive n and w
	// may be compared safely as uint64 before converting them to int64.
	if uint64(n) > uint64(math.MaxInt64)/uint64(segments) {
		return ErrOverflow
	}

	// Each Segment uses three int64 values; its byte count is the stricter
	// output-allocation bound compared with the 8-byte Values slice. The
	// geometry check runs after the finite scan to preserve error precedence.
	// An allowed request may still fail if the operating system has no memory.
	if uint64(segments) > uint64(math.MaxInt)/segmentStorageBytes {
		return ErrOverflow
	}
	return nil
}
