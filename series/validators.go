// Package series validates finite observations before applying causal operations.
// This file centralizes input checks, result allocation, and finite-result policy.
package series

import "math"

// validateValues applies the common unary input policy before any computation.
// It rejects a missing slice, an empty slice, then any nonfinite observation,
// including observations whose transformed positions would be invalid warmup.
//
// Implementation:
//   - Stage 1: Distinguish a nil slice from an allocated empty slice.
//   - Stage 2: Scan every float64 once for NaN or infinity.
//   - Stage 3: Return nil only when the complete input satisfies the policy.
//
// Inputs:
//   - values: caller-owned, read-only slice of input observations.
//
// Returns:
//   - error: ErrNilInput, ErrEmptyInput, ErrNonFinite, or nil in that order.
//
// Determinism:
//   - Checks occur in a fixed order; elements are scanned from index 0 to n-1.
//
// Complexity:
//   - Time O(n), additional space O(1).
//
// Notes:
//   - No input buffers are copied, modified, or retained by validation.
//
// AI-Hints:
//   - Do not bypass finite checking when a lag leaves every output cell invalid.
func validateValues(values []float64) error {
	// Nil and allocated-empty slices have different public error identities.
	if values == nil {
		return ErrNilInput
	}
	if len(values) == 0 {
		return ErrEmptyInput
	}

	// Finiteness precedes every transform-specific domain check.
	return validateFinite(values)
}

// validateFinite checks all float64 observations for NaN and both infinities.
// A single invalid observation is sufficient to reject the entire call,
// regardless of whether its index contributes to a valid transformed value.
//
// Implementation:
//   - Stage 1: Walk input indices in their existing order.
//   - Stage 2: Reject the first NaN or infinite value.
//   - Stage 3: Return nil after the final finite observation.
//
// Inputs:
//   - values: read-only numeric slice; the caller controls shape validation.
//
// Returns:
//   - error: ErrNonFinite on the first invalid element, otherwise nil.
//
// Determinism:
//   - Evaluation order is left-to-right and independent of map or scheduling order.
//
// Complexity:
//   - Time O(n), additional space O(1).
//
// Notes:
//   - This helper does not validate nil or empty shape; its callers own that gate.
//
// AI-Hints:
//   - Do not use epsilon or coercion to turn invalid floats into accepted values.
func validateFinite(values []float64) error {
	for _, value := range values {
		// Either infinity or NaN breaks the finite-observation contract.
		if math.IsNaN(value) || math.IsInf(value, 0) {
			return ErrNonFinite
		}
	}
	return nil
}

// newTransform allocates a detached, equal-length result pair after validation.
// The zero-valued elements implement the warmup rule without filling missing
// observations or allocating an internal shared workspace.
//
// Implementation:
//   - Stage 1: Allocate a float64 values slice with n zero cells.
//   - Stage 2: Allocate an independent bool validity slice with n false cells.
//   - Stage 3: Publish the owned buffers for the calling kernel to populate.
//
// Inputs:
//   - n: validated nonnegative input length; callers ensure n > 0.
//
// Returns:
//   - *TransformResult: two separate, non-nil slices of length n.
//
// Determinism:
//   - All initial Values are +0 and all initial Valid cells are false.
//
// Complexity:
//   - Time O(n), space O(n), due to zero-initialized output storage.
//
// Notes:
//   - Kernel errors discard this unpublished result; no package state retains it.
//
// AI-Hints:
//   - Warmup cells must remain zero/false; do not use NaN as a missing marker.
func newTransform(n int) *TransformResult {
	return &TransformResult{Values: make([]float64, n), Valid: make([]bool, n)}
}

// finiteResult reports whether an arithmetic output remains finite float64.
// It is an output predicate rather than an input sanitizer: callers translate
// false into ErrOverflow without silently clamping an unrepresentable result.
//
// Implementation:
//   - Stage 1: Reject NaN, regardless of its source.
//   - Stage 2: Reject positive or negative infinity.
//   - Stage 3: Accept all remaining finite float64 values, including signed zero.
//
// Inputs:
//   - v: an already computed float64 numeric result.
//
// Returns:
//   - bool: true for finite values, false for NaN or either infinity.
//
// Determinism:
//   - The predicate depends only on the bits of v.
//
// Complexity:
//   - Time O(1), additional space O(1).
//
// Notes:
//   - This does not replace validateFinite on the original input array.
//
// AI-Hints:
//   - Reject infinity generated by subtraction or division even from finite inputs.
func finiteResult(v float64) bool {
	return !math.IsNaN(v) && !math.IsInf(v, 0)
}
