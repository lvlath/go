// Package macd_test exercises the public transition and commit boundaries.
// Its oracles distinguish reachable phase transitions and overflow from
// impossible corruption of private, validated EMA operands.
package macd_test

import (
	"math"
	"testing"

	"github.com/lvlath/go/macd"
)

// TestCoverage_ImplEMA_Lines81_91 pins seed-to-mature transitions using rational
// means and tests extreme constant histories at every stage of the recurrence.
// The historical error branches cannot overflow for finite convex operands;
// the numeric publication gate remains independently tested below.
//
// Implementation:
//   - Stage 1: compare each partial SMA and subsequent EMA with rational oracles.
//   - Stage 2: compare phase counters and independent Line/Signal readiness.
//   - Stage 3: exercise equal and unequal prices at both ends of binary64.
//
// Determinism:
//   - All price fixtures and expected rational means are fixed in sample order.
//
// Complexity:
//   - Time O(n), Space O(1) per history, excluding detached test snapshots.
//
// AI-Hints:
//   - The historical line numbers identify a behavior, not a stable source location.
//   - Do not forge nonfinite means to hit private arithmetic failure branches;
//     Restore must reject those before they ever enter the recurrence.
func TestCoverage_ImplEMA_Lines81_91(t *testing.T) {
	stream, err := macd.NewWithPeriods(2, 3, 2)
	if err != nil {
		t.Fatal(err)
	}
	// Independent rational oracles for [1,2,3,2,5], including the partial
	// signal mean at index 2 and the first mature signal EMA at index 4.
	for i, tc := range []struct {
		price float64
		means [3]float64
		seen  [3]uint64
	}{
		{1, [3]float64{1, 1, 0}, [3]uint64{1, 1, 0}},
		{2, [3]float64{1.5, 1.5, 0}, [3]uint64{2, 2, 0}},
		{3, [3]float64{2.5, 2, 0.5}, [3]uint64{2, 3, 1}},
		{2, [3]float64{13.0 / 6, 2, 1.0 / 3}, [3]uint64{2, 3, 2}},
		{5, [3]float64{73.0 / 18, 3.5, 13.0 / 27}, [3]uint64{2, 3, 2}},
	} {
		point, pushErr := stream.Push(tc.price)
		if pushErr != nil {
			t.Fatal(pushErr)
		}
		saved := stream.Snapshot()
		if saved.Count != uint64(i+1) {
			t.Fatalf("index %d: accepted count %d", i, saved.Count)
		}
		for j := range tc.means {
			mustClose(t, saved.FloatState[j], tc.means[j], "phase mean")
			if saved.IntState[j] != tc.seen[j] {
				t.Fatalf("index %d EMA %d: got %d want %d", i, j, saved.IntState[j], tc.seen[j])
			}
		}
		mustEqualBool(t, point.LineValid, i >= 2, "Line seed completion")
		mustEqualBool(t, point.SignalValid, i >= 3, "Signal seed completion")
	}

	// Both SMA and mature EMA must preserve a constant exactly even at the
	// largest finite value or the smallest strictly positive price.
	for _, price := range []float64{math.MaxFloat64, math.SmallestNonzeroFloat64} {
		stream.Reset()
		for i := 0; i < 12; i++ {
			point, pushErr := stream.Push(price)
			if pushErr != nil {
				t.Fatal(pushErr)
			}
			saved := stream.Snapshot()
			mustBits(t, saved.FloatState[0], price, "constant Fast")
			mustBits(t, saved.FloatState[1], price, "constant Slow")
			mustBits(t, saved.FloatState[2], 0, "constant Signal")
			mustBits(t, point.Histogram, 0, "constant Histogram")
			mustEqualBool(t, point.SignalValid, i >= 3, "constant signal ready")
			// A newly created stream must accept every successful public state.
			clone, newErr := macd.NewWithPeriods(2, 3, 2)
			if newErr != nil {
				t.Fatal(newErr)
			}
			if restoreErr := clone.Restore(saved); restoreErr != nil {
				t.Fatal(restoreErr)
			}
			mustSnapshotsEqual(t, saved, clone.Snapshot())
		}
	}
}

// TestCoverage_ImplMACD_Lines54_58_67_74 verifies the shared numeric admission
// boundary with reachable overflow and rejects invalid intermediate domains
// through the public Restore boundary, without exposing private state.
//
// Implementation:
//   - Stage 1: reject nonfinite Fast/Slow/Signal means, proving atomic Restore.
//   - Stage 2: restore finite, structurally valid adversarial states with ready
//     counters and opposite-sign Line/Signal values near MaxFloat64.
//   - Stage 3: require ErrOverflow and exact rollback for both histogram signs.
//   - Stage 4: retry with a representable price and compare to an untouched stream.
//
// Behavior highlights:
//   - These extreme restored states are structural stress fixtures, not a claim
//     that the means can be generated by an ordinary positive price history.
//   - The invalid-state path must not be opened just to cover a private guard.
//
// Complexity:
//   - Time O(1), Space O(1) for each fixed-size checkpoint/transition.
//
// AI-Hints:
//   - Check every phase field and the full Point, not just accepted Count.
//   - A failed histogram calculation must not advance any EMA.
func TestCoverage_ImplMACD_Lines54_58_67_74(t *testing.T) {
	const fast, slow, signal = 1, 100, 100
	opts := macd.Options{Fast: fast, Slow: slow, Signal: signal}
	for _, tc := range []struct {
		name       string
		means      [3]float64
		bad, retry float64
	}{
		{"positive_histogram_overflow", [3]float64{math.MaxFloat64, math.SmallestNonzeroFloat64, -math.MaxFloat64}, math.MaxFloat64, math.SmallestNonzeroFloat64},
		{"negative_histogram_overflow", [3]float64{math.SmallestNonzeroFloat64, math.MaxFloat64, math.MaxFloat64}, math.SmallestNonzeroFloat64, math.MaxFloat64},
	} {
		t.Run(tc.name, func(t *testing.T) {
			active, err := macd.New(opts)
			if err != nil {
				t.Fatal(err)
			}
			saved := active.Snapshot()
			saved.Count = slow + signal - 1
			saved.IntState = []uint64{fast, slow, signal}
			copy(saved.FloatState, tc.means[:])
			if err = active.Restore(saved); err != nil {
				t.Fatalf("finite structural fixture: %v", err)
			}
			// The former per-EMA error branches require invalid operands. Public
			// Restore refuses NaN and infinity at each of these exact positions.
			for phase := range saved.FloatState {
				for _, invalid := range []float64{math.NaN(), math.Inf(1), math.Inf(-1)} {
					corrupt := active.Snapshot()
					corrupt.FloatState[phase] = invalid
					mustErrorIs(t, active.Restore(corrupt), macd.ErrStateVersion)
					mustSnapshotsEqual(t, saved, active.Snapshot())
				}
			}
			standby, err := macd.New(opts)
			if err != nil {
				t.Fatal(err)
			}
			if err = standby.Restore(saved); err != nil {
				t.Fatal(err)
			}
			// All three means can evolve, but the final signed subtraction cannot
			// be represented. Its rejection must roll back the complete candidate.
			point, pushErr := active.Push(tc.bad)
			mustErrorIs(t, pushErr, macd.ErrOverflow)
			mustMACDPointsEqual(t, point, macd.Point{})
			mustSnapshotsEqual(t, saved, active.Snapshot())
			// The next valid update must use the original state, not any candidate.
			point, pushErr = active.Push(tc.retry)
			if pushErr != nil {
				t.Fatal(pushErr)
			}
			want, pushErr := standby.Push(tc.retry)
			if pushErr != nil {
				t.Fatal(pushErr)
			}
			mustMACDPointsEqual(t, point, want)
			mustSnapshotsEqual(t, standby.Snapshot(), active.Snapshot())
			if active.Snapshot().Count != saved.Count+1 {
				t.Fatal("successful retry did not commit exactly once")
			}
		})
	}

	// The total counter has its own real, earlier overflow gate.
	stream, err := macd.New(opts)
	if err != nil {
		t.Fatal(err)
	}
	saturated := stream.Snapshot()
	saturated.Count = math.MaxUint64
	saturated.IntState = []uint64{fast, slow, signal}
	saturated.FloatState = []float64{1, 1, 0}
	if err = stream.Restore(saturated); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		price float64
		err   error
	}{
		{math.NaN(), macd.ErrNonFinite},
		{0, macd.ErrDomain},
		{1, macd.ErrOverflow},
	} {
		point, pushErr := stream.Push(tc.price)
		mustErrorIs(t, pushErr, tc.err)
		mustMACDPointsEqual(t, point, macd.Point{})
		mustSnapshotsEqual(t, saturated, stream.Snapshot())
	}
}

// FuzzStream_SnapshotRoundTrip checks recoverability for arbitrary binary64
// observations, including nonfinite inputs and extremes outside ordinary prices.
// It verifies every successful transition and every error rollback, not merely
// equality between two calls that happen to share the same arithmetic kernel.
//
// Complexity:
//   - Time O(n), Space O(1) stream state, with bounded test input length.
//
// AI-Hints:
//   - A candidate produced by a successful public Push must be restorable.
//   - Check finiteness and phase identities as well as the continuation bits.
func FuzzStream_SnapshotRoundTrip(f *testing.F) {
	f.Add(uint8(1), uint8(2), uint8(1), uint64(math.Float64bits(1e308)), uint64(math.Float64bits(1)))
	f.Add(uint8(2), uint8(26), uint8(1), uint64(math.Float64bits(math.MaxFloat64)), uint64(1))
	f.Add(uint8(3), uint8(8), uint8(4), uint64(math.Float64bits(math.NaN())), uint64(math.Float64bits(42)))
	f.Fuzz(func(t *testing.T, fastByte, slowByte, signalByte uint8, aBits, bBits uint64) {
		fast := 1 + int(fastByte%7)
		slow := fast + 1 + int(slowByte%11)
		signal := 1 + int(signalByte%9)
		opts := macd.Options{Fast: fast, Slow: slow, Signal: signal}
		active, err := macd.New(opts)
		if err != nil {
			t.Fatal(err)
		}
		standby, err := macd.New(opts)
		if err != nil {
			t.Fatal(err)
		}
		prices := [...]float64{math.Float64frombits(aBits), math.Float64frombits(bBits), 1, math.SmallestNonzeroFloat64, math.MaxFloat64, 101}
		// Enough valid observations remain even if both arbitrary samples fail.
		for i := 0; i < 72; i++ {
			price := prices[i%len(prices)]
			before := active.Snapshot()
			point, pushErr := active.Push(price)
			if pushErr != nil {
				if math.IsNaN(price) || math.IsInf(price, 0) {
					mustErrorIs(t, pushErr, macd.ErrNonFinite)
				} else if price <= 0 {
					mustErrorIs(t, pushErr, macd.ErrDomain)
				} else {
					mustErrorIs(t, pushErr, macd.ErrOverflow)
				}
				mustMACDPointsEqual(t, point, macd.Point{})
				mustSnapshotsEqual(t, before, active.Snapshot())
				continue
			}
			if math.IsNaN(price) || math.IsInf(price, 0) || price <= 0 {
				t.Fatal("accepted invalid price")
			}
			want, pushErr := standby.Push(price)
			if pushErr != nil {
				t.Fatal(pushErr)
			}
			mustMACDPointsEqual(t, point, want)
			saved := active.Snapshot()
			if saved.Count != before.Count+1 {
				t.Fatal("accepted count did not advance exactly once")
			}
			if fast == 1 {
				mustBits(t, saved.FloatState[0], price, "Fast=1")
			}
			if signal == 1 && point.LineValid {
				mustBits(t, point.Line, point.Signal, "Signal=1")
				if point.Histogram != 0 {
					t.Fatal("nonzero unit-weight Histogram")
				}
			}
			if err = standby.Restore(saved); err != nil {
				t.Fatalf("successful Push exported invalid state: %v", err)
			}
			mustSnapshotsEqual(t, saved, standby.Snapshot())
		}
	})
}
